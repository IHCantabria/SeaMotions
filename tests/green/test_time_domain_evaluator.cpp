
// Test suite for the time-domain Green's function evaluators implemented in
// src/green/time_domain_evaluator.hpp.
//
// Structural tests (no data files required):
//   1. test_block_hash_2d  – verify that eval_time_residual_2d selects the
//      correct block for several (beta, log_mu) points in the dGdtC database.
//   2. test_1d_A_evaluator – verify that eval_time_1d returns ≈ 1.0 for
//      the dGdtA0C type (which stores a constant A_0(mu) ≈ 1.0).
//   3. test_G0_basis_dGdt  – spot-check dGdt_G0_basis against the known
//      analytic formula at a point where the result is non-trivial.
//   4. test_G0_basis_chain – verify the derivative-chain relationship
//      dGdtx_G0_basis = (-beta^2/4) * dGdt_G0_basis.
//   5. test_residual_finite – verify that eval_time_residual_2d returns a
//      finite value for several (beta, mu) inputs in the dGdtC domain.
//   6. test_combined_dGdt  – verify that eval_dGdt returns a finite,
//      non-zero value and that varying mu changes the result.
//   7. test_all_evaluators_finite – all six evaluators return finite values.
//
// Reference-data tests (require file paths via argv[1..6]):
//   8. test_against_reference<eval_fn> – compare each evaluator against
//      reduced reference values derived from the original integral databases
//      (generated by aux_tools/generate_time_domain_test_data.py).
//      Acceptance criterion (per point):
//        |computed - expected| <= abs_tol + rel_tol * |expected|
//      with per-function tolerances set to 5 × the Chebyshev fit tolerance.

