static constexpr int N_SPOT = static_cast<int>( sizeof( SPOT_PTS ) / sizeof( SPOT_PTS[0] ) );


// ============================================================================
// Test 1 – spot-checks against Python reference
// ============================================================================
static void test_spot_checks()
{
    int n_checked = 0;
    int n_skipped = 0;

    // Lambda: check one (computed, expected) pair.
    auto check_val = [&]( cusfloat computed, double expected,
                          double beta, double mu, const char* fname )
    {
        if ( std::abs( expected ) < MIN_SKIP )
        {
            ++n_skipped;
            return;
        }
        const cusfloat exp_f = static_cast<cusfloat>( expected );
        const cusfloat diff  = std::abs( computed - exp_f );
        const bool     ok    = diff <= SPOT_ABS_TOL + SPOT_REL_TOL * std::abs( exp_f );

        if ( !ok )
        {
            std::cerr << std::scientific << std::setprecision( 10 )
                      << "  FAIL  " << fname
                      << "  beta=" << beta << "  mu=" << mu
                      << "  expected=" << expected
                      << "  computed=" << static_cast<double>( computed )
                      << "  rel_err="  << static_cast<double>( diff / std::abs( exp_f ) )
                      << "\n";
        }

        std::string tag = std::string( fname ) + "_spot_b"
            + std::to_string( static_cast<int>( beta ) )
            + "_m" + std::to_string( mu );
        check( ok, fname );
        ++n_checked;
    };

    for ( int i = 0; i < N_SPOT; ++i )
    {
        const SpotPt& s = SPOT_PTS[i];
        const cusfloat b = static_cast<cusfloat>( s.beta );
        const cusfloat m = static_cast<cusfloat>( s.mu   );

        // dGdt: Python includes f0; use default config (use_f0 = true).
        check_val( dGdt_asymptotic  ( b, m ),                      s.dGdt,   s.beta, s.mu, "dGdt"   );
        // dGdtt/dGdttt/dGdtx/dGdttx: Python omits the df0 term (commented
        // out); use TDAsympConfig{false,15} to match Python exactly.
        const TDAsympConfig no_f0{ false, 15 };
        check_val( dGdtt_asymptotic ( b, m, no_f0 ), s.dGdtt,  s.beta, s.mu, "dGdtt"  );
        check_val( dGdttt_asymptotic( b, m, no_f0 ), s.dGdttt, s.beta, s.mu, "dGdttt" );
        check_val( dGdtx_asymptotic ( b, m, no_f0 ), s.dGdtx,  s.beta, s.mu, "dGdtx"  );
        check_val( dGdttx_asymptotic( b, m, no_f0 ), s.dGdttx, s.beta, s.mu, "dGdttx" );
    }

    std::cout << "  " << n_checked << " pairs checked, "
              << n_skipped << " pairs skipped (|ref| < " << MIN_SKIP << ")\n";
}


// ============================================================================
// Data loader for Test 2
// File format:  line 1 = N (integer)
//               lines 2..N+1 = beta  mu  value  (space-separated)
// ============================================================================
struct DatPoint
{
    cusfloat beta;
    cusfloat mu;
};

static std::vector<DatPoint> load_dat( const std::string& path )
{
    std::ifstream f( path );
    if ( !f )
        throw std::runtime_error( "Cannot open file: " + path );

    int n = 0;
    f >> n;
    if ( n <= 0 )
        throw std::runtime_error( "Invalid point count in: " + path );

    std::vector<DatPoint> pts;
    pts.reserve( static_cast<std::size_t>( n ) );

    for ( int i = 0; i < n; ++i )
    {
        double b = 0.0, m = 0.0, val = 0.0;
        f >> b >> m >> val;
        if ( !f )
            throw std::runtime_error( "Read error in: " + path );
        DatPoint dp;
        dp.beta = static_cast<cusfloat>( b );
        dp.mu   = static_cast<cusfloat>( m );
        pts.push_back( dp );
    }
    return pts;
}


// ============================================================================
// Test 2 – finiteness over the full (beta, mu) grid from a dat file
// ============================================================================
using AsympFn = cusfloat (*)( cusfloat, cusfloat, TDAsympConfig );

static void test_finiteness( const std::string& path,
                              AsympFn            fn,
                              const char*        label )
{
    const std::vector<DatPoint> pts = load_dat( path );
    int n_bad = 0;

    for ( std::size_t i = 0; i < pts.size(); ++i )
    {
        const cusfloat result = fn( pts[i].beta, pts[i].mu, TDAsympConfig{} );
        if ( !std::isfinite( result ) )
        {
            std::cerr << "  FAIL  " << label
                      << "  idx="  << i
                      << "  beta=" << static_cast<double>( pts[i].beta )
                      << "  mu="   << static_cast<double>( pts[i].mu   )
                      << "  result=" << static_cast<double>( result )
                      << "\n";
            ++n_bad;
        }
    }

    check( n_bad == 0, label );
    std::cout << "  " << label << ": " << pts.size() << " points, all finite\n";
}


// ============================================================================
// main
// ============================================================================
int main( int argc, char** argv )
{
    if ( argc < 6 )
    {
        std::cerr << "Usage: " << argv[0]
                  << "  dGdt.dat  dGdtt.dat  dGdttt.dat  dGdtx.dat  dGdttx.dat\n";
        return 1;
    }

    int exit_code = 0;

    // ---- Test 1 ----
    std::cout << "=== test_spot_checks ===\n";
    try
    {
        test_spot_checks();
        std::cout << "PASS\n\n";
    }
    catch ( const std::exception& ex )
    {
        std::cerr << "EXCEPTION: " << ex.what() << "\n";
        exit_code = 1;
    }

    // ---- Test 2 ----
    std::cout << "=== test_finiteness ===\n";
    try
    {
        test_finiteness( argv[1], dGdt_asymptotic,   "dGdt"   );
        test_finiteness( argv[2], dGdtt_asymptotic,  "dGdtt"  );
        test_finiteness( argv[3], dGdttt_asymptotic, "dGdttt" );
        test_finiteness( argv[4], dGdtx_asymptotic,  "dGdtx"  );
        test_finiteness( argv[5], dGdttx_asymptotic, "dGdttx" );
        std::cout << "PASS\n";
    }
    catch ( const std::exception& ex )
    {
        std::cerr << "EXCEPTION: " << ex.what() << "\n";
        exit_code = 1;
    }

    return exit_code;
}
