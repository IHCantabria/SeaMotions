// Test suite for the time-domain asymptotic Green function routines implemented
// in src/green/time_domain_asymptotic.hpp / .cpp.
//
// Test 1 – spot_checks
//   Compare each of the five functions (dGdt, dGdtt, dGdttt, dGdtx, dGdttx)
//   against Python-generated reference values at a 4×3 (beta, mu) grid.
//   Reference produced by running:
//       aux_tools/time_domain_asymptotic.py::{dG*}_asymptotic(beta, mu)
//   with the default configuration (nmax=15, use_f0=true).
//   Acceptance criterion for each point:
//       |computed - expected| <= ABS_TOL + REL_TOL * |expected|
//   Points with |expected| < MIN_SKIP are skipped (near-machine-zero values
//   that arise from the exp(-beta^2 * mu / 4) decay at large beta and mu).
//
// Test 2 – finiteness
//   Load each of the five reference .dat files (passed as argv[1..5]).
//   For every (beta, mu) pair in the file, call the corresponding C++ routine
//   and assert that the result is finite (no NaN, no inf).
//
// Usage:
//   test_time_domain_asymptotic_cmd  dGdt.dat  dGdtt.dat  dGdttt.dat  \
//                                    dGdtx.dat  dGdttx.dat

#include <cmath>
