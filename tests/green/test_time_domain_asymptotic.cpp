// ============================================================================
// Precision-adaptive tolerances
// ============================================================================
// At small β (≤ 5) the asymptotic series is poorly converged and the heavy
// cancellation among the 15 inner terms amplifies FP round-off differences
// between Intel ICX and Python/NumPy.  At β ≥ 10 the relative error is below
// 1e-5; at β ≥ 20 it is below 1e-8.  We therefore choose 5e-4 as a single
// tolerance that is robust at β = 5 yet tight enough to catch any genuine
// implementation error (wrong sign, wrong coefficient, wrong formula).
//
// Note: the Python dGdtt/dGdttt/dGdtx/dGdttx functions omit the f0-derivative
// term (it is commented out).  To produce a fair comparison the spot-check
// calls those four C++ functions with use_f0 = false (matching Python).
// dGdt includes f0 in both Python and C++ so it is tested with the default
// configuration.
//
// Reference values whose magnitude is below MIN_SKIP are skipped; this avoids
// points where the f0 contribution dominates and the Python reference is
// effectively zero while the C++ (with use_f0 = true) is not.
#ifdef SIMPLE_PREC
static constexpr cusfloat SPOT_REL_TOL = static_cast<cusfloat>( 1e-3 );
static constexpr cusfloat SPOT_ABS_TOL = static_cast<cusfloat>( 1e-5 );
#else
static constexpr cusfloat SPOT_REL_TOL = static_cast<cusfloat>( 5e-4 );
static constexpr cusfloat SPOT_ABS_TOL = static_cast<cusfloat>( 1e-9 );
#endif

// Skip spot-check comparison when |expected| < MIN_SKIP.
// Set to 1.0 so that near-zero f0-dominated points (large β, large μ) where
// Python returns ≈ 0 but C++ (with use_f0) returns the f0 contribution are
// not compared against the Python reference.
static constexpr double MIN_SKIP = 1.0;


// ============================================================================
// Helpers
// ============================================================================
static void check( bool cond, const char* msg )
{
    if ( !cond )
    {
        std::cerr << "FAIL  " << msg << std::endl;
        throw std::runtime_error( msg );
    }
}


