# ---------------------------------------------------------------------------
# Formatting helpers
# ---------------------------------------------------------------------------

COLS = 6    # hex-float literals per source line (~132 chars per line)

def array_body( arr ):
    """Return lines of C++ hex-float literals for a flat numpy float64 array.

    Uses Python's float.hex() which produces valid C++17 hex float literals
    (e.g. '0x1.3ae147ae147aep+0') with exact binary round-trip.
    """
    n     = len( arr )
    lines = []
    for i in range( 0, n, COLS ):
        chunk = arr[i : i + COLS]
        parts = [ float(v).hex() for v in chunk ]
        line  = "    " + ", ".join( parts )
        if i + COLS < n:
            line += ","
        lines.append( line )
    return "\n".join( lines )


# ---------------------------------------------------------------------------
# Load all HDF5 tables
# ---------------------------------------------------------------------------

def load_tables():
    """Return (beta, mu, fcn_dict) where fcn_dict[name] is a flat float64 array."""
    beta0 = mu0 = None
    fcn_data = {}
    for name in TABLES:
        path = os.path.join( DB_DIR, name + ".h5" )
        if not os.path.exists( path ):
            sys.exit( f"ERROR: cannot find {path}" )
        with h5py.File( path, "r" ) as f:
            beta = np.array( f["beta"], dtype=np.float64 )
            mu   = np.array( f["mu"],   dtype=np.float64 )
            fcn  = np.array( f["fcn"],  dtype=np.float64 )   # shape (n_beta, n_mu)

        if beta0 is None:
            beta0, mu0 = beta, mu
        else:
            if not np.array_equal( beta, beta0 ):
                sys.exit( f"ERROR: beta axis differs in {name}" )
            if not np.array_equal( mu, mu0 ):
                sys.exit( f"ERROR: mu axis differs in {name}" )

        fcn_data[name] = fcn.ravel( order="C" )   # row-major: [i*n_mu + j]
        print( f"  Loaded {name}: {len(beta):4d} x {len(mu):3d} = {len(fcn_data[name]):,} doubles" )

    return beta0, mu0, fcn_data


# ---------------------------------------------------------------------------
# Write td_database.hpp
# ---------------------------------------------------------------------------

def write_header( n_beta, n_mu ):
    size = n_beta * n_mu

    extern_fcn = "\n".join(
        f"    extern const double {name.lower()}_fcn[{size}];"
        for name in TABLES
    )

    make_ncs = "\n\n".join(
        f"""\
    inline NaturalCubicSpline2D<double> make_ncs_{name}()
    {{
        return NaturalCubicSpline2D<double>( N_BETA, beta, N_MU, mu, {name.lower()}_fcn );
    }}"""
        for name in TABLES
    )

    make_bilin = "\n\n".join(
        f"""\
    inline Bilinear2D<double> make_bilinear_{name}()
    {{
        return Bilinear2D<double>( N_BETA, beta, N_MU, mu, {name.lower()}_fcn );
    }}"""
        for name in TABLES
    )

    make_catrom = "\n\n".join(
        f"""\
    inline BicubicCatmullRom2D<double> make_catmullrom_{name}()
    {{
        return BicubicCatmullRom2D<double>( N_BETA, beta, N_MU, mu, {name.lower()}_fcn );
    }}"""
        for name in TABLES
    )

    text = f"""\
{LICENSE}
#pragma once

// ---------------------------------------------------------------------------
// td_database.hpp
//
// Provides embedded access to the 7 time-domain integral tables:
//   Gt, Gtt, Gttt, Gtx, Gttx, Gtxx, Gttxx
//
// All tables share the same beta[] and mu[] axes.
//
// Quick start
// -----------
//   #include "src/green/td_data/td_database.hpp"
//
//   // Construct once (NCS runs the Thomas-algorithm solver — negligible cost)
//   auto ncs_Gt = td_db::make_ncs_Gt();
//
//   // Evaluate many times
//   double val = ncs_Gt.eval( beta, std::log10(mu) );
//
// The make_ncs_*(), make_bilinear_*(), and make_catmullrom_*() functions
// construct independent interpolator objects from the embedded constant arrays.
// Store them as member variables or static locals if you need repeated access.
// ---------------------------------------------------------------------------

#include "../../math/data_fit/interp2d.hpp"

namespace td_db {{

// ---------------------------------------------------------------------------
// Grid dimensions (all 7 tables share the same beta and mu axes)
// ---------------------------------------------------------------------------
static constexpr int N_BETA = {n_beta};   // beta: 0 .. {float(n_beta-1)*0.01:.2f} (step 0.01)
static constexpr int N_MU   = {n_mu};    // mu  : 1e-4 .. 0.9999 (log-spaced)

// Shared axes (defined in td_common_axes.cpp)
extern const double beta[{n_beta}];   // linear beta values
extern const double mu[{n_mu}];       // linear mu values (pass to constructor; NCS stores log10 internally)

// Function value arrays, row-major: fcn[i*N_MU + j] = f(beta[i], mu[j])
// (defined in td_Gt_fcn.cpp .. td_Gttxx_fcn.cpp)
{extern_fcn}

// ---------------------------------------------------------------------------
// NaturalCubicSpline2D factory functions — recommended for production
//   C2 in log(mu), C1 in beta; best accuracy among the three methods
// ---------------------------------------------------------------------------
{make_ncs}

// ---------------------------------------------------------------------------
// BicubicCatmullRom2D factory functions — no precomputation, C1 everywhere
// ---------------------------------------------------------------------------
{make_catrom}

// ---------------------------------------------------------------------------
// Bilinear2D factory functions — lightest weight, C0
// ---------------------------------------------------------------------------
{make_bilin}

}} // namespace td_db
"""
    path = os.path.join( OUT_DIR, "td_database.hpp" )
    with open( path, "w", encoding="utf-8" ) as f:
        f.write( text )
    print( f"  -> {os.path.relpath( path, PROJECT_ROOT )}" )


# ---------------------------------------------------------------------------
# Write td_common_axes.cpp
# ---------------------------------------------------------------------------

def write_axes_cpp( beta, mu ):
    n_beta, n_mu = len(beta), len(mu)
    text  = LICENSE + "\n"
    text += '#include "td_database.hpp"\n\n'
    text += "namespace td_db {\n\n"
    text += f"const double beta[{n_beta}] = {{\n"
    text += array_body( beta ) + "\n"
    text += "};\n\n"
    text += f"const double mu[{n_mu}] = {{\n"
    text += array_body( mu ) + "\n"
    text += "};\n\n"
    text += "} // namespace td_db\n"

    path = os.path.join( OUT_DIR, "td_common_axes.cpp" )
    with open( path, "w", encoding="utf-8" ) as f:
        f.write( text )
    print( f"  -> {os.path.relpath( path, PROJECT_ROOT )}" )


# ---------------------------------------------------------------------------
# Write td_<Name>_fcn.cpp
# ---------------------------------------------------------------------------

def write_fcn_cpp( name, flat_fcn ):
    n       = len( flat_fcn )
    varname = name.lower() + "_fcn"

    text  = LICENSE + "\n"
    text += '#include "td_database.hpp"\n\n'
    text += "namespace td_db {\n\n"
    text += f"const double {varname}[{n}] = {{\n"
    text += array_body( flat_fcn ) + "\n"
    text += "};\n\n"
    text += "} // namespace td_db\n"

    path = os.path.join( OUT_DIR, f"td_{name}_fcn.cpp" )
    with open( path, "w", encoding="utf-8" ) as f:
        f.write( text )
    print( f"  -> {os.path.relpath( path, PROJECT_ROOT )}" )


