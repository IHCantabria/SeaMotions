"""
generate_td_interp_headers.py
====================================
Reads the 7 time-domain integral HDF5 databases and generates C++ source files
that embed the tabulated data directly into the executable, removing the HDF5
runtime dependency.

All 7 tables share identical beta[] and mu[] axes, so those are written once
to td_common_axes.cpp.  Each table's fcn[] is written to its own .cpp file
(one translation unit per table for parallel compilation).

Output directory  :  src/green/td_data/
Generated files   :
  td_database.hpp        — dimensions, extern declarations, factory functions
  td_common_axes.cpp     — shared beta[N_BETA] and mu[N_MU]
  td_Gt_fcn.cpp
  td_Gtt_fcn.cpp
  td_Gttt_fcn.cpp
  td_Gtx_fcn.cpp
  td_Gttx_fcn.cpp
  td_Gtxx_fcn.cpp
  td_Gttxx_fcn.cpp

Usage (from project root):
  python aux_tools/generate_td_interp_headers.py

After generation, add the .cpp files to the CMake target (see printed
instructions at the end of the run).
"""

